const normalized=api.normalize({sigunguCd:'1',bjdongCd:'2',bun:'3'},[{hoNm:'226',flrNoNm:'2층'}],[{hoNm:'226',flrNoNm:'2층',area:'93.56',exposPubuseGbCd:'1'},{hoNm:'226',flrNoNm:'지1층',area:'97.28',exposPubuseGbCd:'2'}]);
